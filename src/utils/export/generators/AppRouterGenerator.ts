import JSZip from 'jszip'

export function generateAppRouter(zip: JSZip, project: any, models: any[]) {
  const appFolder = zip.folder('src/app')
  if (!appFolder) return

  const projectName = project.name || 'Metabuilder App'

  appFolder.file('globals.css', `@tailwind base;
@tailwind components;
@tailwind utilities;`)

  // Root Layout
  appFolder.file('layout.tsx', `import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "${projectName}",
  description: "Enterprise app generated by MetaBuilderPRO",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="pt-BR">
      <body className={inter.className}>{children}</body>
    </html>
  );
}
`)

  // Dashboard Group Layout (Sidebar navigation)
  const dashboardFolder = appFolder.folder('(dashboard)')
  if (dashboardFolder) {
    const navLinks = models.map(m => `
            <Link href="/${m.table_name}" className="flex items-center gap-3 rounded-lg px-3 py-2 text-neutral-500 transition-all hover:text-neutral-900 hover:bg-neutral-100">
              {/* Adicione um ícone aqui se desejar */}
              ${m.name}
            </Link>`).join('')

    dashboardFolder.file('layout.tsx', `import Link from "next/link"

export default function DashboardLayout({ children }: { children: React.ReactNode }) {
  return (
    <div className="grid min-h-screen w-full lg:grid-cols-[280px_1fr]">
      <div className="hidden border-r bg-neutral-50/40 lg:block">
        <div className="flex h-full max-h-screen flex-col gap-2">
          <div className="flex h-[60px] items-center border-b px-6">
            <Link className="flex items-center gap-2 font-semibold" href="/">
              <span className="text-indigo-600 font-black tracking-tight">${projectName}</span>
            </Link>
          </div>
          <div className="flex-1 overflow-auto py-2">
            <nav className="grid items-start px-4 text-sm font-medium">
              <Link href="/" className="flex items-center gap-3 rounded-lg px-3 py-2 text-neutral-500 transition-all hover:text-neutral-900 hover:bg-neutral-100">
                Início
              </Link>
              <div className="my-2 border-t" />
              <div className="px-3 py-2 text-xs font-semibold text-neutral-400 uppercase tracking-wider">
                Módulos
              </div>
${navLinks}
            </nav>
          </div>
        </div>
      </div>
      <div className="flex flex-col">
        <header className="flex h-[60px] items-center gap-4 border-b bg-neutral-50/40 px-6">
          <div className="w-full flex-1">
            {/* Adicione breadcrumbs ou barra de busca aqui */}
          </div>
        </header>
        <main className="flex flex-1 flex-col gap-4 p-4 md:gap-8 md:p-6 bg-white">
          {children}
        </main>
      </div>
    </div>
  )
}
`)

    // Home Page inside (dashboard)
    dashboardFolder.file('page.tsx', `export default function Home() {
  return (
    <div className="flex flex-col items-center justify-center h-full text-center space-y-4">
      <div className="inline-flex items-center justify-center px-4 py-1.5 rounded-full bg-indigo-50 text-indigo-600 text-sm font-bold tracking-widest uppercase mb-4">
        MetaBuilderPRO Architecture
      </div>
      <h1 className="text-4xl font-black tracking-tight">
        Bem-vindo ao ${projectName}
      </h1>
      <p className="text-lg text-neutral-500 max-w-2xl mx-auto">
        Código fonte exportado com sucesso. Arquitetura Modular (FSD) pronta para ser escalada pelo seu time de desenvolvedores sêniores.
      </p>
      
      <div className="pt-8 grid grid-cols-1 md:grid-cols-2 gap-4 text-left max-w-3xl w-full">
        <div className="p-6 bg-white rounded-2xl shadow-sm border border-neutral-200">
          <h3 className="font-bold mb-2">📁 src/features</h3>
          <p className="text-sm text-neutral-500">Módulos isolados por domínio de negócio. Contém as regras de negócio, chamadas de API e componentes específicos.</p>
        </div>
        <div className="p-6 bg-white rounded-2xl shadow-sm border border-neutral-200">
          <h3 className="font-bold mb-2">📁 src/components/ui</h3>
          <p className="text-sm text-neutral-500">Componentes visuais agnósticos e reutilizáveis (Botões, Modais, Inputs), padrão Shadcn.</p>
        </div>
      </div>
    </div>
  );
}
`)

    // Create a dynamic route for each model
    models.forEach(m => {
      const modelRoute = dashboardFolder.folder(m.table_name)
      if (modelRoute) {
        modelRoute.file('page.tsx', `import { ${m.name.replace(/\s/g, '')}List } from "@/features/${m.table_name}/components/${m.name.replace(/\s/g, '')}List"
import { fetch${m.name.replace(/\s/g, '')}s } from "@/features/${m.table_name}/actions"

export default async function ${m.name.replace(/\s/g, '')}Page() {
  const data = await fetch${m.name.replace(/\s/g, '')}s()

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-2xl font-bold tracking-tight">${m.name}</h2>
        <p className="text-neutral-500">Gerencie os registros de ${m.name.toLowerCase()}</p>
      </div>
      <${m.name.replace(/\s/g, '')}List initialData={data} />
    </div>
  )
}
`)
      }
    })
  }
}
