export function nodeEnvExample(ast: AppAST): string {
  const db: string[] = []
  switch (ast.dbStack) {
    case 'oracle':
      db.push('# Banco Oracle: host:porta/NOME_DO_SERVICO (ex.: dbserver:1521/FREEPDB1), usuário e senha do esquema do app')
      db.push('DB_CONNECTION_STRING=')
      db.push('DB_USER=')
      db.push('DB_PASSWORD=')
      break
    case 'mysql':
      db.push('# Conexão do banco (ex.: mysql://usuario:senha@dbserver:3306/banco)')
      db.push('DATABASE_URL=')
      break
    case 'sqlserver':
      db.push('# Conexão do banco (ex.: Server=dbserver,1433;Database=banco;User Id=usuario;Password=senha;Encrypt=true)')
      db.push('DATABASE_URL=')
      break
    default:
      db.push('# Conexão do banco (ex.: postgres://usuario:senha@dbserver:5432/banco)')
      db.push('DATABASE_URL=')
  }
  const ldap = ast.authConfig?.authType === 'ldap'
    ? ['', '# Login por LDAP / Active Directory', 'LDAP_URL=', 'LDAP_BASE_DN=', 'LDAP_BIND_DN=', 'LDAP_BIND_PASSWORD=', 'LDAP_SEARCH_FILTER=(sAMAccountName={{username}})']
    : []
  const supa = ast.dbStack === 'supabase' ? ['', '# Supabase (valores públicos, usados na compilação da imagem)', 'NEXT_PUBLIC_SUPABASE_URL=', 'NEXT_PUBLIC_SUPABASE_ANON_KEY='] : []
  return `# =========================================================================
# .env.example — variáveis do app em PRODUÇÃO
# Copie para ".env" (ao lado do docker-compose.prod.yml) e preencha. Sem aspas. Nunca publique o .env.
# Generated by MetaBuilder Pro
# =========================================================================

# Endereço público do app (HTTPS automático). localhost = só para testar. Atrás de balanceador com HTTPS: :80
DOMAIN=localhost

${db.join('\n')}

# Assina a sessão de login (mínimo 32 caracteres). Gere um valor próprio: openssl rand -hex 32
# Com várias instâncias do app, o valor precisa ser o MESMO em todas.
MB_SESSION_SECRET=

# Pasta das cópias das exportações (dentro do contêiner; é um volume) e por quanto tempo ficam (horas; 0 = não expira)
EXPORT_DIR=/data/exports
EXPORT_RETENTION_HOURS=${ast.downloadRetentionHours === null ? 0 : (ast.downloadRetentionHours ?? 24)}
${[...ldap, ...supa].join('\n')}
`
}

function nodeCompose(ast: AppAST): string {
  const slug = slugOf(ast)
  const buildArgs = [
    ...(ast.projectId ? [`        NEXT_PUBLIC_PROJECT_ID: "${ast.projectId}"`] : []),
    ...(ast.dbStack === 'supabase' ? ['        NEXT_PUBLIC_SUPABASE_URL: ${NEXT_PUBLIC_SUPABASE_URL:-}', '        NEXT_PUBLIC_SUPABASE_ANON_KEY: ${NEXT_PUBLIC_SUPABASE_ANON_KEY:-}'] : []),
  ]
  return `# =========================================================================
# docker-compose.prod.yml — PRODUÇÃO: o app + proxy reverso com HTTPS.
# O banco NÃO está aqui: use o banco do cliente (veja DATABASE_URL ou DB_* no .env).
# Subir:  docker compose -f docker-compose.prod.yml up -d --build
# Generated by MetaBuilder Pro
# =========================================================================

services:
  app:
    build:
      context: .
${buildArgs.length ? `      args:\n${buildArgs.join('\n')}\n` : ''}    image: ${slug}-app:latest
    container_name: ${slug}-app
    restart: unless-stopped
    env_file: .env
    environment:
      PORT: "3000"
      EXPORT_DIR: /data/exports
    volumes:
      - exports:/data/exports
    expose:
      - "3000"
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3000/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 15s
      timeout: 5s
      retries: 5
      start_period: 40s

  proxy:
    image: caddy:2-alpine
    container_name: ${slug}-proxy
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
    environment:
      DOMAIN: \${DOMAIN:-localhost}
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy_data:/data
      - caddy_config:/config
    depends_on:
      app:
        condition: service_healthy

volumes:
  exports:
  caddy_data:
  caddy_config:
`
}

export function addNodeDeployPack(ast: AppAST, files: Map<string, string>): void {
  const publicArgs = [
    ...(ast.projectId ? [{ name: 'NEXT_PUBLIC_PROJECT_ID', value: ast.projectId }] : []),
    ...(ast.dbStack === 'supabase' ? [{ name: 'NEXT_PUBLIC_SUPABASE_URL', value: '' }, { name: 'NEXT_PUBLIC_SUPABASE_ANON_KEY', value: '' }] : []),
  ]
  files.set('Dockerfile', nextDockerfile({ dir: '.', port: 3000, publicArgs, comment: 'Dockerfile — app Next.js (Node.js)' }))
  files.set('.dockerignore', NEXT_DOCKERIGNORE)
  files.set('docker-compose.prod.yml', nodeCompose(ast))
  files.set('Caddyfile', caddyfile('app:3000'))
  files.set('.env.example', nodeEnvExample(ast))
  files.set('app/api/health/route.ts', HEALTH_ROUTE)
  files.set('DEPLOY.md', deployGuide(ast, 'node'))
}

