import { AppAST } from '../ast'

/**
 * deploy-pack.ts
 *
 * Pacote de produção que acompanha cada app gerado (Node e Java, com Postgres ou Oracle):
 *   - Dockerfile(s) multi-stage, imagem enxuta, usuário sem privilégios e health check;
 *   - docker-compose.prod.yml: o app e um proxy reverso (Caddy) com HTTPS automático. O BANCO NÃO ENTRA: é o do cliente;
 *   - Caddyfile, .env.example (só nomes: os segredos o cliente fornece), .dockerignore;
 *   - rota /api/health (sem login) para health check de contêiner, balanceador e Kubernetes;
 *   - DEPLOY.md: como subir por Docker Compose, em Windows Server sem Docker e em Kubernetes/nuvem.
 *
 * Nada aqui muda a lógica do app. O modo `standalone` do Next só liga no build do Docker (MB_STANDALONE=1): `next start` e os testes seguem iguais.
 */

const HEALTH_ROUTE = `import { NextResponse } from 'next/server'

// Health check para contêiner, balanceador e Kubernetes: responde sem login e sem tocar no banco.
export const dynamic = 'force-dynamic'

export function GET() {
  return NextResponse.json({ status: 'ok' })
}
`

const slugOf = (ast: AppAST) => (ast.projectSlug || 'app').toLowerCase().replace(/[^a-z0-9-]/g, '-')

export function caddyfile(upstream: string): string {
  return `# Proxy reverso com HTTPS automático (Caddy).
# DOMAIN = o endereço público do app (ex.: app.suaempresa.com.br): o certificado é emitido e renovado sozinho (portas 80 e 443 abertas na internet).
# DOMAIN=localhost usa um certificado local, só para testar. Atrás de um balanceador que já faz o HTTPS, use DOMAIN=:80.
{$DOMAIN:localhost} {
	encode zstd gzip
	header {
		X-Content-Type-Options nosniff
		Referrer-Policy strict-origin-when-cross-origin
		-Server
	}
	reverse_proxy ${upstream}
}
`
}

function nextDockerfile(opts: { dir: string; port: number; publicArgs: Array<{ name: string; value?: string }>; comment: string }): string {
  const args = opts.publicArgs.map(a => `ARG ${a.name}${a.value !== undefined ? `=${a.value}` : ''}\n`).join('')
  const envs = opts.publicArgs.map(a => `ENV ${a.name}=$${a.name}\n`).join('')
  return `# =========================================================================
# ${opts.comment}
# Multi-stage: instala, compila (Next.js em modo standalone) e roda só o necessário.
# Generated by MetaBuilder Pro
# =========================================================================

# ── 1. Dependências ──
FROM node:22-bookworm-slim AS deps
WORKDIR /app
COPY package.json package-lock.json* .npmrc* ./
RUN if [ -f package-lock.json ]; then npm ci; else npm install; fi

# ── 2. Build ──
FROM node:22-bookworm-slim AS build
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
# valores NEXT_PUBLIC_* são gravados no código na compilação (não são segredos)
${args}${envs}ENV MB_STANDALONE=1 NEXT_TELEMETRY_DISABLED=1
RUN mkdir -p public scripts db && npm run build

# ── 3. Imagem final ──
FROM node:22-bookworm-slim AS run
WORKDIR /app
ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 PORT=${opts.port} HOSTNAME=0.0.0.0 EXPORT_DIR=/data/exports
RUN groupadd --system app && useradd --system --gid app --create-home app && mkdir -p /data/exports && chown -R app:app /data
COPY --from=build --chown=app:app /app/.next/standalone ./
COPY --from=build --chown=app:app /app/.next/static ./.next/static
COPY --from=build --chown=app:app /app/public ./public
COPY --from=build --chown=app:app /app/scripts ./scripts
COPY --from=build --chown=app:app /app/db ./db
USER app
EXPOSE ${opts.port}
HEALTHCHECK --interval=15s --timeout=5s --start-period=40s --retries=5 \\
  CMD node -e "fetch('http://127.0.0.1:${opts.port}/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"
CMD ["node", "server.js"]
`
}

