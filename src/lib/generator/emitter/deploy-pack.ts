export function addJavaDeployPack(ast: AppAST, files: Map<string, string>, backendDockerfile: string): void {
  // o frontend lê a URL do backend em tempo de execução (API_URL); aqui só o que é público e fixo na compilação
  files.set('frontend/Dockerfile', nextDockerfile({ dir: 'frontend', port: 3000, publicArgs: [], comment: 'Dockerfile — frontend Next.js (consome a API Spring Boot)' }))
  files.set('frontend/.dockerignore', NEXT_DOCKERIGNORE)
  if (!files.has('backend/Dockerfile')) files.set('backend/Dockerfile', backendDockerfile)
  files.set('backend/.dockerignore', `target\n.git\n.env\n.env.*\n!.env.example\n*.log\n`)
  files.set('docker-compose.prod.yml', javaCompose(ast))
  files.set('Caddyfile', caddyfile('frontend:3000'))
  files.set('.env.example', javaEnvExample(ast))
  files.set('frontend/app/api/health/route.ts', HEALTH_ROUTE)
  files.set('DEPLOY.md', deployGuide(ast, 'java'))
}

